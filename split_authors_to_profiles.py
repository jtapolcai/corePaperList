#!/usr/bin/env python3
"""
One-time migration: split authors.json into per-author profiles/*.json files.

For authors that already have a profile file: only adds fields that are NOT
already present in the profile (existing profile data is never overwritten).
For authors without a profile file: creates a new file with all fields.

Fields NOT written to profiles (they are auto-generated by compile_authors_json.py):
  core_astar, core_a, core_b, core_c, no_core,
  core_astar_papers, core_a_papers,
  core_astar_equiv, first_author_core_astar_equiv, hungarian_core_astar_equiv,
  years_since_phd, category_astar_rank, age_astar_rank

Run once:
  python3 split_authors_to_profiles.py
"""
import json
from pathlib import Path

BASE = Path(__file__).parent
AUTHORS_JSON = BASE / "authors.json"
PROFILES_DIR = BASE / "profiles"

# These are auto-computed each run — don't persist in profile files
GENERATED_FIELDS = {
    "core_astar", "core_a", "core_b", "core_c", "no_core",
    "core_astar_papers", "core_a_papers",
    "core_astar_equiv", "first_author_core_astar_equiv", "hungarian_core_astar_equiv",
    "years_since_phd", "category_astar_rank", "age_astar_rank",
}

PROFILES_DIR.mkdir(exist_ok=True)

authors = json.loads(AUTHORS_JSON.read_text(encoding="utf-8"))
created = updated = skipped = 0

for author in authors:
    slug = author.get("slug")
    if not slug:
        continue

    profile_file = PROFILES_DIR / f"{slug}.json"
    from_authors = {k: v for k, v in author.items() if k not in GENERATED_FIELDS and v not in (None, "", [], {})}

    if profile_file.exists():
        existing = json.loads(profile_file.read_text(encoding="utf-8"))
        # Merge: only add fields not already present
        added = {k: v for k, v in from_authors.items() if k not in existing}
        if added:
            merged = {**existing, **added}
            profile_file.write_text(json.dumps(merged, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
            updated += 1
        else:
            skipped += 1
    else:
        profile_file.write_text(json.dumps(from_authors, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        created += 1

print(f"Done: {created} created, {updated} updated (new fields added), {skipped} unchanged.")
print(f"Total profiles: {len(list(PROFILES_DIR.glob('[!_]*.json')))}")
